/**
 * Regenerates `src/data/avatarPixels.ts` from `src/assets/image.png`.
 *
 * The Hero avatar is drawn as a grid of block glyphs (one `<span>` per cell),
 * so the image is downsampled once at authoring time and stored as a compact
 * string: 3 base-36 characters per pixel, each digit being one of six colour
 * levels per channel (a 216-colour palette).
 *
 * The grid keeps the source image's aspect ratio exactly — no cropping — so the
 * avatar is never squashed. `RESOLUTION` controls how many cells the longest
 * edge gets; the other edge follows from the image proportions.
 *
 * Each side is rounded to an even number so the grid stays crisp.
 *
 * Usage: node scripts/generate-avatar-pixels.mjs
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = "src/assets/image.png";
const OUT = "src/data/avatarPixels.ts";

/** Number of cells along the longest edge of the rendered grid. */
const RESOLUTION = 32;

/** Six levels per channel keeps the data small and the posterised look intact. */
const LEVELS = 6;
const DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz";

const toLevel = (v) => Math.round((v / 255) * (LEVELS - 1));

const source = sharp(SRC);
const meta = await source.metadata();
const aspect = meta.width / meta.height;

// Round the short edge, then derive the long edge so the ratio is preserved.
const COLS = aspect >= 1 ? RESOLUTION : Math.max(2, Math.round(RESOLUTION * aspect));
const ROWS = aspect >= 1 ? Math.max(2, Math.round(RESOLUTION / aspect)) : RESOLUTION;

const { data, info } = await source
  // `fill` samples the whole image: nothing is cropped, so proportions hold.
  .resize(COLS, ROWS, { fit: "fill" })
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

let flat = "";
for (let y = 0; y < info.height; y++) {
  for (let x = 0; x < info.width; x++) {
    const i = (y * info.width + x) * info.channels;
    flat += DIGITS[toLevel(data[i])] + DIGITS[toLevel(data[i + 1])] + DIGITS[toLevel(data[i + 2])];
  }
}

const contents = `// AUTO-GENERATED by scripts/generate-avatar-pixels.mjs — do not edit by hand.
// Source: src/assets/image.png (${meta.width}x${meta.height}, aspect ${aspect.toFixed(4)})
// Grid: ${COLS}x${ROWS} cells, 3 base-36 chars each, ${LEVELS} colour levels per channel.

export const avatarCols = ${COLS};
export const avatarRows = ${ROWS};

/** Source image aspect ratio, used to keep the rendered grid undistorted. */
export const avatarAspect = ${aspect.toFixed(6)};

/** Maps a colour level (0-${LEVELS - 1}) to its 0-255 channel value. */
export const avatarLevel = (level: number) =>
  Math.round((level / ${LEVELS - 1}) * 255);

export const avatarPixels =
  "${flat}";
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, contents);

console.log(
  `wrote ${OUT} (${COLS}x${ROWS} = ${COLS * ROWS} cells, aspect ${aspect.toFixed(3)}, ${contents.length} bytes)`,
);
